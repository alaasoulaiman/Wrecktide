"""import_ui_textures.py - import Content\\UI\\Textures\\*.png as UTexture2D under /Game/UI/Textures.

Same shape as Tools\\import_sfx.py: AssetImportTask, replace existing, automated, save. Idempotent and
fail-closed (a missing asset after the import is a FAIL, not a shrug). Markers: WRECKTIDE-UIART.

The source PNGs are generated by tools\\gen_ui_art.py. UI textures get UserInterface2D compression and
no mip maps so the panel stays crisp at any window size, and sRGB stays on (they are colour, not data).

Usage: run_py_args.cmd <this file>
"""
import os
import unreal

M = "WRECKTIDE-UIART"
DEST = "/Game/UI/Textures"


def log(msg):
    unreal.log_warning("%s %s" % (M, msg))


def fatal(msg):
    unreal.log_error("%s FATAL %s" % (M, msg))
    unreal.log_error("%s RESULT=FAIL" % M)
    raise SystemExit(1)


src = os.path.join(unreal.Paths.project_content_dir(), "UI", "Textures")
src = os.path.abspath(src)
if not os.path.isdir(src):
    fatal("no source folder %s (run tools\\gen_ui_art.py first)" % src)

pngs = sorted(f for f in os.listdir(src) if f.lower().endswith(".png"))
if not pngs:
    fatal("no png files in %s" % src)

tasks = []
for f in pngs:
    task = unreal.AssetImportTask()
    task.set_editor_property("filename", os.path.join(src, f))
    task.set_editor_property("destination_path", DEST)
    task.set_editor_property("destination_name", os.path.splitext(f)[0])
    task.set_editor_property("replace_existing", True)
    task.set_editor_property("automated", True)
    task.set_editor_property("save", True)
    tasks.append(task)

unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)

ok = 0
for f in pngs:
    name = os.path.splitext(f)[0]
    path = "%s/%s" % (DEST, name)
    if not unreal.EditorAssetLibrary.does_asset_exist(path):
        log("MISSING after import: %s" % path)
        continue
    asset = unreal.EditorAssetLibrary.load_asset(path)
    if asset is None:
        log("MISSING after load: %s" % path)
        continue
    dirty = False
    if asset.get_editor_property("compression_settings") != unreal.TextureCompressionSettings.TC_EDITOR_ICON:
        asset.set_editor_property("compression_settings", unreal.TextureCompressionSettings.TC_EDITOR_ICON)
        dirty = True
    if asset.get_editor_property("mip_gen_settings") != unreal.TextureMipGenSettings.TMGS_NO_MIPMAPS:
        asset.set_editor_property("mip_gen_settings", unreal.TextureMipGenSettings.TMGS_NO_MIPMAPS)
        dirty = True
    if not asset.get_editor_property("srgb"):
        asset.set_editor_property("srgb", True)
        dirty = True
    if dirty:
        unreal.EditorAssetLibrary.save_loaded_asset(asset, only_if_is_dirty=False)
    log("imported %s (%dx%d, %s)" % (path, asset.blueprint_get_size_x(), asset.blueprint_get_size_y(),
                                     asset.get_class().get_name()))
    ok += 1

if ok != len(pngs):
    fatal("imported %d of %d" % (ok, len(pngs)))
log("RESULT=OK %d textures under %s" % (ok, DEST))
